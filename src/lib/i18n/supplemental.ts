const translations = new Map(supplementalPhrases.map(row => [row[0], row]));

export function supplementalTranslation(locale: Exclude<Locale, 'ko'>, source: string): string | undefined {
  const exact = translations.get(source)?.[locale === 'ja' ? 2 : 1];
  if (exact !== undefined) return exact;
  const more = source.match(/^외 (\d+)건$/);
  if (more) return locale === 'ja' ? `ほか${more[1]}件` : `+${more[1]} more`;
  const designCount = source.match(/^(\d+)개의 (편집 가능한 디자인|디자인 레퍼런스)$/);
  if (designCount) return locale === 'ja'
    ? `${translations.get(designCount[2])?.[2]}${designCount[1]}件`
    : `${designCount[1]} ${translations.get(designCount[2])?.[1]}`;
  const won = source.match(/^([\d,]+)원$/);
  if (won) return `₩${won[1]}`;
  const assemblyLevel = source.match(/^(\d+)단 (후면 보강대 체결|가로판 놓기|세로판 세우기)$/);
  if (assemblyLevel) return locale === 'ja'
    ? `${assemblyLevel[1]}段目：${translations.get(assemblyLevel[2])?.[2]}`
    : `Level ${assemblyLevel[1]}: ${translations.get(assemblyLevel[2])?.[1]}`;
  const payment = source.match(/^([₩$¥€\d,.\s]+(?:원)?) 결제하기$/);
  if (payment) {
    const amount = payment[1].endsWith('원') ? `₩${payment[1].slice(0, -1)}` : payment[1];
    return locale === 'ja' ? `${amount}を支払う` : `Pay ${amount}`;
  }
  return undefined;
}
