const dictionaries = Object.fromEntries(phrases.flatMap(row => row.map(source => [source, row]))) as Record<string, readonly [string, string, string]>;

export function translate(source: string, language: UILanguage): string {
  const index = language === 'ko' ? 0 : language === 'ja' ? 2 : 1;
  const key = source === 'ON' ? 'On' : source === 'OFF' ? 'Off' : source;
  const phrase = Object.hasOwn(dictionaries, key) ? dictionaries[key] : undefined;
  if (phrase) return phrase[index];
  // Labels with stable numeric values: translate the copy without changing the value.
  const numbered = source.match(/^(수납 구성|수납|구획) (\d+)( 편집)?$/);
  if (numbered) return `${translate(numbered[1], language)} ${numbered[2]}${numbered[3] ? ` ${translate('편집', language)}` : ''}`;
  const ceiling = source.match(/^천장 높이 ([\d.]+)cm 이상이 필요합니다\.$/);
  if (ceiling) return language === 'en' ? `Requires a ceiling height of at least ${ceiling[1]} cm.` : language === 'ja' ? `天井の高さは${ceiling[1]}cm以上必要です。` : source;
  const width = source.match(/^전체 너비 ([\d.]+)cm$/);
  if (width) return language === 'en' ? `Total width ${width[1]} cm` : language === 'ja' ? `全体の幅 ${width[1]}cm` : source;
  const cable = source.match(/^케이블 홀 · ([\d.]+)cm$/);
  if (cable) return `${translate('케이블 구멍', language)} · ${cable[1]}cm`;
  if (/^[CNS]_/.test(source)) return translate(source.slice(2), language);
  if (source.includes('+')) return source.split('+').map(part => translate(part, language)).join(' + ');
  if (source.includes(' · ')) return source.split(' · ').map(part => translate(part, language)).join(' · ');
  return source;
}
